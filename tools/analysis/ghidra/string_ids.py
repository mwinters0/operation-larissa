"""String-table ids of ONWIN32.EXE as names (pure Python, no Ghidra; the program side is generate_string_ids.py).

The game loads every caption, prompt and message with `LoadStringResource(id, buffer, size)` (a wrapper of LoadStringA) and the
help dialog with `RunHelpTopic(first_item, string_id, logical_id)`, always with a number such as 0x2b66. string_ids_onwin32.json
maps every id of the string table to a name (`{"11110": "STR_CORRECT_PHRASE_0", ...}`): names only, never the text, which is
the game's. From it and the call sites the program yields, this module makes three things in annotations_onwin32.json:

  * the enum `/neptune/StringId` (every name = its id), the type of the id parameter of both functions, so the decompiler
    writes `STR_...` where a constant is passed;
  * one equate per name with a reference at every instruction that holds the constant (a `PUSH imm`, or the `ADD reg, imm` /
    `LEA reg, [reg + imm]` that makes `base + index` for a family of consecutive strings), so the Listing shows it too;
  * the two signatures with the enum as the id parameter's type.

Equates and the enum are rebuilt from scratch each time (an equate named in the names file that no site uses any more is removed),
so the result depends only on the names file and the program.

Teaches: generating annotation entries from a naming table instead of typing them, keeping the generated part separable.
"""
import json
from pathlib import Path

import annotations as an

NAMES_FILE = "string_ids_onwin32.json"
ENUM_PATH = "/neptune/StringId"
ENUM_SIZE = 4
ENUM_COMMENT = "Ids of the string table (LoadStringResource, RunHelpTopic). Generated by generate_string_ids.py from string_ids_onwin32.json."
# function entry -> (index of its id parameter): the functions whose caller passes a string-table id
ID_PARAMETERS = {"0x00411726": 0, "0x00428d70": 1}


def load_names(path):
    """{id: name}: the names file; a name is unique and starts with STR_."""
    names = {int(k): v for k, v in json.loads(Path(path).read_text()).items()}
    if len(set(names.values())) != len(names) or not all(n.startswith("STR_") for n in names.values()):
        raise ValueError("%s: names must be unique and start with STR_" % NAMES_FILE)
    return names


def name_of(names, value):
    """The name of an id; an id the names file lacks gets the stable fallback STR_<4 digits> (and is told by the caller)."""
    return names.get(value, "STR_%04d" % value)


def enum_definition(names, used=()):
    values = {name_of(names, v): v for v in sorted(set(names) | set(used))}
    return {"kind": "enum", "size": ENUM_SIZE, "values": values, "comment": ENUM_COMMENT}


def equates_for(names, sites):
    """sites: [(value, "0x004120f1", operand index)] -> {name: {"value", "refs": ["address:operand"]}} (refs sorted, unique)."""
    out = {}
    for value, address, op in sites:
        equate = out.setdefault(name_of(names, value), {"value": value, "refs": []})
        ref = "%s:%d" % (address, op)
        if ref not in equate["refs"]:
            equate["refs"].append(ref)
    for equate in out.values():
        equate["refs"].sort()
    return out


def with_ids(doc, names, sites, signatures, function_names=None):
    """The annotation document with the string-id part regenerated.

    signatures: {function entry: signature dict as the file writes it} for the functions of ID_PARAMETERS; the id parameter
    is given the enum type. function_names: entry -> name written beside a function (as the export writes it; none for an
    ONWIN.MAP name). Everything that is not a generated equate, the enum or those signatures is kept as it is."""
    flat = an.flatten(doc)
    used = {v for v, _, _ in sites}
    generated = {name_of(names, v) for v in set(names) | used}
    for k in [k for k in flat if k[0] == "equates" and k[1] in generated]:
        del flat[k]
    for name, equate in equates_for(names, sites).items():
        flat[("equates", name)] = equate
    flat[("types", ENUM_PATH)] = enum_definition(names, used)
    for entry, signature in signatures.items():
        index = ID_PARAMETERS[entry]
        params = list(signature["params"])
        _, pname = an.parse_param(params[index])
        params[index] = an.param_text(ENUM_PATH, pname)
        flat[("functions", entry, "signature")] = dict(signature, params=params)
    fn_names = {entry: v["name"] for entry, v in doc.get("functions", {}).items() if "name" in v}
    fn_names.update(function_names or {})
    return an.unflatten(flat, fn_names)
